#!/usr/bin/env python3
"""Batch runner for de-asm survey probe experiments (lrflags.py at scale).

Input: a probe config JSON -- a list of entries shaped exactly like
swap.json entries (rva/obj/src/maps/patch/aliases/span) plus an optional
"flags" per probe. Typical config: build/survey/probes/<wave>_probes.json,
generated by the experiment author from src/* spellings.

Flow: compile all probe sources in chunked docker containers (~180/cmdline,
E2BIG ceiling), fitobj-judge each against the FA chunk with the entry's
own maps/patches, then report: EXACT / FIT-OK(with patch) / FAIL per probe.

Usage:
    python3 build/survey/hybrid_probe.py <config.json> [--keep]
Probes and their objs land in build/survey/probes/ (never in build/pilot/,
so a broken probe can never leak into a real link).
"""
import json
import os
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(REPO)
sys.path.insert(0, os.path.join(REPO, "tools"))
import swap  # noqa: E402  (re-uses DOCKER_PLAIN + _fit plumbing)

DOCKER_PLAIN = swap.DOCKER_PLAIN


def step_compile(probes, outdir):
    os.makedirs(outdir, exist_ok=True)
    fails = set()
    per = 180
    for i in range(0, len(probes), per):
        parts = []
        for p in probes[i:i + per]:
            cl = ("wine Z:/opt/msvc420/bin/CL.EXE /nologo "
                  + p.get("flags", "/c /O2 /Gy /G5")
                  + " Z:/work/%s /FoZ:/work/%s/%s.obj"
                  % (p["src"], outdir, p["obj"]))
            parts.append('( %s ) && echo __OK__%s || echo __FAIL__%s'
                         % (cl, p["obj"], p["obj"]))
        r = subprocess.run(DOCKER_PLAIN % dict(uid=os.getuid(),
                                               gid=os.getgid(),
                                               cmd="; ".join(parts)),
                           shell=True, capture_output=True, text=True)
        out = r.stdout + r.stderr
        oks = {l[len("__OK__"):].strip() for l in out.splitlines()
               if l.startswith("__OK__")}
        fails |= {l[len("__FAIL__"):].strip() for l in out.splitlines()
                  if l.startswith("__FAIL__")}
        for p in probes[i:i + per]:
            if p["obj"] in oks and os.path.exists(
                    "%s/%s.obj" % (outdir, p["obj"])):
                print("cl %-32s ok" % p["obj"])
            else:
                fails.add(p["obj"])
    return fails


def judge(probe, outdir):
    """fitobj the probe against its FA chunk; return (rc, output)."""
    args = [sys.executable, "tools/fitobj.py",
            "%s/%s.obj" % (outdir, probe["obj"]), "%#x" % probe["rva"]]
    for m in probe.get("maps", []):
        args += ["--map", m]
    for p in probe.get("patch", []):
        args += ["--patch", p]
    if probe.get("span"):
        args += ["--span", str(probe["span"])]
    for a in probe.get("aliases", []):
        args += ["--alias", a]
    r = subprocess.run(args, capture_output=True, text=True)
    return r.returncode, (r.stdout + r.stderr)


def main():
    cfg = sys.argv[1:]
    files = [a for a in cfg if not a.startswith("-")]
    keep = "--keep" in cfg
    es = []
    for f in files:
        es += json.load(open(f))
    outdir = "build/survey/probes"
    # compile with each probe's own flags: group by flag string for the
    # batched call (flag is per-invocation in CL).
    fails = set()
    done = 0
    by_flags = {}
    for p in es:
        by_flags.setdefault(p.get("flags", "/c /O2 /Gy /G5"), []).append(p)
    for fl, group in by_flags.items():
        for p in group:
            p["flags"] = fl
        fails |= step_compile(group, outdir)
    print("== judged (%d exact-fit verdicts)" % (len(es) - len(fails)))
    exact = []
    for p in es:
        if p["obj"] in fails:
            print("compile FAIL %s" % p["obj"])
            continue
        rc, out = judge(p, outdir)
        done += 1
        last = out.strip().splitlines()[-1] if out.strip() else ""
        if rc == 0:
            exact.append(p["obj"])
            print("EXACT  %-32s  %s" % (p["obj"], last))
            if not keep:
                os.remove("%s/%s.obj" % (outdir, p["obj"]))
                for suf in ("_fit",):
                    fp = "%s/%s%s.obj" % (outdir, p["obj"], suf)
                    if os.path.exists(fp):
                        os.remove(fp)
        else:
            print("no     %-32s  %s" % (p["obj"], last[:90]))
    print("== %d/%d exact" % (len(exact), len(es)))


if __name__ == "__main__":
    main()