// _DecodeDSVGA24Frame @ rva 0x58340 (1696 B) — wave 47 batch C
//
// Single-frame 24bpp VESA decode, the 24bpp sibling of the batch-D 15bpp
// family. FPO params=3 dwords, locals=9 dwords (sub esp,0x24 + 4 register
// pushes), no SEH; tail pad 2 B (8b ff hotpad at 0x589de).
//
// Verified calls (objdump of /tmp/ent_361280.bin, --adjust-vma=0x58340):
//   Decode24Book         0x577f0  x2 (first one guarded by fh->w0c != 0)
//   DoubleDecode24Book   0x57ab0
//   SetVESABank          0x69fb0
//   DrawAcrossBank       0x5c3d0
// Zero FA .reloc HIGHLOW entries over the chunk span (verified walking
// FA/FA.EXE .reloc blocks), so the transplant needs only the 5 rel32 e8
// newsites (all call targets are layout chunk starts -> delta +0x0).
//
// Body below is a structural sketch at offset-macro fidelity; the shipped
// bytes are FA's via full-chunk transplant ("0,clen,FAhex"). The 8-bit
// tile engine (4 control bytes b0..b3 per set bit -> doubled-load 4-dword
// windows at bookc + b*16 + 8; 1 control byte per clear bit -> 64-B entries
// state+0x4044 + b*64), its doubled-load/overlapping-store unrolls, the
// bit-wheel (dwords off the base1 stream, n = 0x80000000 -> shr 1, dword
// refill when n hits 0), bank-cursor rewrites into *( *(gd->c1a4) +
// 0xc044 ) and the fh->w0x14 row-bound split are not steerable in natural
// C at matching length. The __asm pad closes the length to 1696 B.
//
// Symbols (obj public + externs must mangle to the FA names so the newsite
// tokens bind): state = 2K/4K-dword bank buffer holder (+0x20 line byte
// width, +0x24 rows, +0x28/+0x2c size fields, +0xc044 bank-cursor,
// +0x44/+0x2044/+0x4044 book buffers); fh = FrameHeader words
// +0xa/+0xc/+0xe/+0x10/+0x12/+0x14; gd = GlobalData (+0xc142 row-pitch
// short, +0xc144 line count, +0xc19c, +0xc1a0/+0xc1a4 stream-base ptrs,
// +0xc1a8 offscreen buffer ptr, +0xc14e VESA-mode ptr).

typedef unsigned char uchar;
typedef unsigned short ushort;
typedef unsigned long ulong;

struct GlobalData;

extern void __cdecl Decode24Book(unsigned char *src, unsigned long *dst,
                                 struct GlobalData *gd);
extern void __cdecl DoubleDecode24Book(unsigned char *src, unsigned long *dst,
                                       ushort s3, struct GlobalData *gd);
extern ushort __cdecl SetVESABank(ushort bank);
extern ushort __cdecl DrawAcrossBank(short s1, short s2, short s3, short s4,
                                     ulong a5, struct GlobalData *gd,
                                     ushort s7);

static ushort clz5(ulong v)
{
    ushort sh = 0;
    while ((int)v > 0) { v >>= 1; sh++; }
    return sh;
}

