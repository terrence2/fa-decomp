        base = (ulong)*(ulong **)((char *)gd + 0xc1a4)
             + 24 * (*(ushort *)((char *)fh + 10) + 1)
             + c12 + (ulong)fh;
        Decode24Book((uchar *)base, (unsigned long *)sp1, gd);                // book A -> state+0x2044
        *(ulong **)(*(ulong **)((char *)gd + 0xc1a4) + 0xc044) = (ulong *)base;
