    dx = (ulong)*(ushort *)((char *)fh + 12);                // fh->w0c
    sum = dx
        + (ulong)(*(ushort *)((char *)fh + 14)               // fh->w0e
        + (ulong)*(ushort *)((char *)fh + 10));              // fh->w0a
    c12 = (ulong)*(ushort *)((char *)fh + 18);               // fh->w12 (u16)
    edi2 = (12 * (sum + 1)) * 2;                             // 0x18*(sum+1)
    pos1 = (ulong)*(ulong **)((char *)gd + 0xc1a0) + c12 + edi2;
    pos = (ulong)fh + pos1;                                  // bit-reader cursor
    bytes = (uchar *)(pos1 - edi2);                          // ctrl-byte stream
    sp1 = (long *)((char *)state + 0x2044);
